/** Chinese UI for Chinese Obsidian locales, English for everything else. */
export function t(key: Key, vars?: Record<string, string | number>): string {
	const table: Record<Key, string> = moment.locale().toLowerCase().startsWith("zh") ? zh : en;
	let text = table[key];
	for (const [name, value] of Object.entries(vars ?? {})) text = text.replace(`{${name}}`, String(value));
	return text;
}
